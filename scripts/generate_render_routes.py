"""Generate the single public-only Render Blueprint from reviewed draft route metadata.

Only the static informational service goes in render.yaml. Private paid infrastructure is
opt-in and intentionally NOT in the root Blueprint. No wildcard SPA rewrite is permitted.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "src/curriculum/public-catalog.json"
OUTPUT = ROOT / "render.yaml"


def config() -> str:
    catalog = json.loads(CATALOG.read_text())
    courses = catalog["courses"]
    if catalog["reviewStatus"] != "unreviewed-draft" or len(courses) != 44:
        raise ValueError("Render guide must use the 44-course unreviewed metadata projection")
    slugs = [course["slug"] for course in courses]
    if len(set(slugs)) != 44 or any(
        not slug or not all(char.islower() or char.isdigit() or char == "-" for char in slug)
        for slug in slugs
    ):
        raise ValueError("Render course paths must be distinct, simple slugs")
    paths = ["/courses", "/how-it-works", "/availability"]
    paths += [f"/courses/{slug}" for slug in slugs]
    routes = "".join(
        f"      - type: rewrite\n        source: {path}\n        destination: /index.html\n"
        for path in paths
    )
    return (
        "# Public-only Render static site. Manually review copy, costs and exact rules before linking.\n"
        "# The private adult service and database are NOT created by this Blueprint.\n"
        "# Generated by scripts/generate_render_routes.py; never use a /* rewrite.\n"
        "services:\n"
        "  - type: web\n"
        "    name: desloop-readonly-guide\n"
        "    runtime: static\n"
        "    branch: main\n"
        "    autoDeployTrigger: 'off'\n"
        "    buildCommand: npm ci --ignore-scripts && npm run build:render-public\n"
        "    staticPublishPath: ./dist/render-public\n"
        "    headers:\n"
        "      - path: /*\n"
        "        name: X-Content-Type-Options\n"
        "        value: nosniff\n"
        "      - path: /*\n"
        "        name: Referrer-Policy\n"
        "        value: strict-origin-when-cross-origin\n"
        "      - path: /*\n"
        "        name: Content-Security-Policy\n"
        '        value: "default-src \'self\'; script-src \'self\'; style-src \'self\' \'unsafe-inline\'; img-src \'self\' data:; font-src \'self\' data:; connect-src \'none\'; object-src \'none\'; base-uri \'self\'; frame-ancestors \'none\'"\n'
        "      - path: /release.json\n"
        "        name: Cache-Control\n"
        "        value: no-store\n"
        "    # Domain root is served directly by index.html. Other pages have exact rewrites.\n"
        "    routes:\n"
        + routes
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = config()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit("Render Blueprint differs from the exact 44-course public-only routes")
        print("Render Blueprint has 47 exact informational rewrites; no private service or wildcard")
    else:
        OUTPUT.write_text(expected)
        print("Wrote public-only render.yaml with 47 exact informational rewrites")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
